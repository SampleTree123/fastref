#!/usr/bin/env python3
"""CPU audit of actual editing evidence, not correctness labels or visual quality.

python scripts/editing_agent/audit_runtime.py --run RUN --dataset PUBLIC.jsonl
Add --probe for ffprobe geometry checks; --legacy-v2 explicitly skips the new
output-only observation requirement and must not be reported as a v3 pass.
"""
import argparse
from fractions import Fraction
import hashlib
import json
import os
from pathlib import Path
import subprocess
import time


ROOT = Path(__file__).resolve().parents[2]


def digest(value):
    return hashlib.sha256(json.dumps(value, ensure_ascii=False, sort_keys=True,
                                    separators=(',', ':')).encode()).hexdigest()


def read(path):
    return json.loads(Path(path).read_text())


def require(condition, path, message):
    if not condition:
        raise ValueError(f'{path}: {message}')


def same_path(a, b):
    return Path(a).resolve() == Path(b).resolve()


def semantics(request, hashes, worker):
    return digest({'source_sha256': hashes[0], 'prompt': request['prompt'].strip(),
                   'references': [{'sha256': sha, 'type': ref['type'], 'view': ref.get('view', '')}
                                  for ref, sha in zip(request['references'], hashes[1:])],
                   'seed': request.get('seed', 42), 'worker_identity_sha256': worker})


class Auditor:
    def __init__(self, run, *, probe=False, legacy_v2=False):
        self.run, self.probe, self.legacy = Path(run).resolve(), probe, legacy_v2
        self.hashes, self.probed = {}, {}
        self.worker_ids = {digest(read(p)) for p in (self.run / 'queues').glob('*/worker_identity.json')}

    def file_sha(self, path):
        p = Path(path).resolve(); stat = p.stat()
        require(p.is_file() and stat.st_size > 0, p, 'missing or empty file')
        key = (str(p), stat.st_size, stat.st_mtime_ns, stat.st_ctime_ns)
        if key not in self.hashes:
            with p.open('rb') as handle:
                self.hashes[key] = hashlib.file_digest(handle, 'sha256').hexdigest()
        return self.hashes[key]

    def inputs(self, request):
        return [self.file_sha(p) for p in [request['source_video'], *[r['path'] for r in request['references']]]]

    def native(self, path):
        record = read(path)
        require(record['status'] == 'ok', path, 'native generation was not successful')
        require(record['execution_sha256'] == digest({'request': record['request'],
                    'media_sha256': record['input_media_sha256'], 'worker': record['worker_identity_sha256']}),
                path, 'execution digest differs')
        require(self.inputs(record['request']) == record['input_media_sha256'], path, 'actual input bytes differ')
        require(same_path(record['video_path'], Path(path).parent / 'edited.mp4'), path, 'output is not the committed generated MP4')
        require(self.file_sha(record['video_path']) == record['video_sha256'], path, 'actual generated bytes differ')
        require(Path(record['video_path']).stat().st_size == record['bytes'], path, 'generated byte count differs')
        return record

    def generation(self, directory, progress):
        generation = progress['generation']; native_path = directory / 'generation/editing_generation.json'
        proof_path = directory / 'generation/reuse_provenance.json'
        require(generation.get('status') == 'ok', directory, 'progress has no successful generation')
        if generation.get('reuse_provenance'):
            require(not native_path.exists(), native_path, 'reused output must not have a fabricated new native receipt')
            proof = read(proof_path)
            require(proof == generation['reuse_provenance'], proof_path, 'reuse proof differs from progress')
            require(proof['kind'] == 'previous_actual_ltx_generation', proof_path, 'unsupported reuse provenance')
            previous = Path(proof['previous_receipt']).resolve()
            require(previous.is_relative_to((Path(proof['previous_run']) / 'cases').resolve()) and
                    previous.name == 'editing_generation.json', proof_path, 'reuse receipt is outside previous actual generations')
            require(self.file_sha(previous) == proof['previous_receipt_sha256'], proof_path, 'previous receipt bytes changed')
            old = self.native(previous)
            require(old['execution_sha256'] == proof['previous_execution_sha256'], proof_path, 'previous execution differs')
            request = proof['current_request']; inputs = self.inputs(request)
            require(inputs == proof['input_media_sha256'], proof_path, 'reuse current input bytes differ')
            worker = proof['worker_identity_sha256']
            require(worker == old['worker_identity_sha256'], proof_path, 'reuse model differs')
            require(semantics(request, inputs, worker) == proof['semantic_key_sha256'] ==
                    semantics(old['request'], old['input_media_sha256'], worker), proof_path, 'reuse computation is not equivalent')
            require(same_path(proof['video_path'], old['video_path']) and proof['video_sha256'] == old['video_sha256'],
                    proof_path, 'reuse did not return the verified generated video')
            record = {**old, 'request': request}
        else:
            require(not proof_path.exists(), proof_path, 'unclaimed reuse proof')
            record = self.native(native_path)
        require(record['worker_identity_sha256'] in self.worker_ids, directory, 'no matching actual worker identity')
        require(same_path(generation['video_path'], record['video_path']) and
                generation['video_sha256'] == record['video_sha256'], directory, 'progress output differs from receipt')
        require(same_path(record['request']['output_dir'], directory / 'generation'), directory, 'request output directory differs')
        if self.probe and record['video_sha256'] not in self.probed:
            envroot = ROOT.parent / 'ltx2.5/runtime/envs/trainer'
            env = dict(os.environ, CUDA_VISIBLE_DEVICES='', LD_LIBRARY_PATH=str(envroot / 'lib') + ':' + os.environ.get('LD_LIBRARY_PATH', ''))
            result = subprocess.run([str(envroot / 'bin/ffprobe'), '-v', 'error', '-select_streams', 'v:0',
                '-show_entries', 'stream=width,height,avg_frame_rate,nb_frames', '-of', 'json', record['video_path']],
                env=env, capture_output=True, text=True, check=True)
            info = json.loads(result.stdout)['streams'][0]
            require(Fraction(info['avg_frame_rate']) == 12 and int(info['nb_frames']) == 121 and
                    (info['width'], info['height']) in ((768, 448), (448, 768)), record['video_path'], 'unexpected output geometry or sampling')
            self.probed[record['video_sha256']] = info
        return record

    def output_observation(self, directory, progress, card, state):
        if self.legacy:
            expected = progress['review']['card']
            for key in ('observed', 'uncertain'):
                require(card[key] == expected[key], directory, 'legacy card differs from its review')
            return 'legacy_v2_independence_not_checked'
        path = directory / 'output_observation/card.json'
        observed = read(path)
        for key in ('observed', 'uncertain'):
            require(card[key] == observed[key], path, 'final card was changed after independent observation')
            require(progress['review']['card'][key] == observed[key], path, 'comparison review rewrote the independent card')
        require(same_path(observed['video_path'], card['video_path']) and observed['video_id'] == card['video_id'],
                path, 'observation belongs to another video')
        calls = sorted((directory / 'output_observation').glob('observe_call_*.json'))
        require(bool(calls), directory / 'output_observation', 'no raw output-only observation call evidence')
        valid = []
        for call_path in calls:
            call = read(call_path); messages = call['messages']
            require(len(messages) >= 2 and messages[0] == {'role': 'system', 'content': state['identity']['prompts']['observe']},
                    call_path, 'observation system prompt differs')
            expected = [{'type': 'text', 'text': "Describe this video's actual visible contents."},
                        {'type': 'video', 'path': str(Path(card['video_path']).resolve()), 'media_role': 'history'}]
            require(messages[1] == {'role': 'user', 'content': expected}, call_path,
                    'observation contains source, request, references, or unexpected input')
            for message in messages[2:]:
                require(message['role'] in ('assistant', 'user') and isinstance(message['content'], str),
                        call_path, 'unexpected observation correction input')
                if message['role'] == 'user':
                    require(message['content'].startswith('The previous tool call was not executed. Error: '),
                            call_path, 'extra user instruction in observation')
            if call.get('status') == 'valid':
                valid.append(call['parsed_call']['arguments'])
        require(len(valid) == 1, path, 'expected one accepted independent observation')
        require(all(valid[0][k] == observed[k] for k in ('observed', 'uncertain')), path, 'observation differs from accepted model answer')
        return 'output_only_observation_verified'

    def chain(self, row):
        directory = self.run / 'cases' / row['chain_id']; state_path = directory / 'state.json'
        state = read(state_path) if state_path.is_file() else {}
        if state.get('status') != 'completed':
            return {'id': row['chain_id'], 'status': 'skipped_not_completed', 'runtime_status': state.get('status', 'absent')}
        result = {'id': row['chain_id'], 'status': 'passed', 'turns': [], 'failures': []}
        try:
            history = state['history']; videos = history['videos']; edits = history['edits']
            require(len(videos) == len(row['turns']) + 1 and len(edits) == len(row['turns']), state_path, 'history length differs')
            require([v['video_id'] for v in videos] == list(range(len(videos))), state_path, 'history IDs are not consecutive')
            require(same_path(videos[0]['video_path'], row['root_video']) and videos[0]['parent_id'] is None, state_path, 'root was replaced')
            require(state['completed_turns'] == len(row['turns']) and state['identity']['chain'] == row,
                    state_path, 'completed count or original public input differs')
            if not self.legacy:
                require(read(directory / 'videos/video_000.json') == videos[0], directory / 'videos/video_000.json',
                        'root card differs from final history')
            self.file_sha(row['root_video'])
        except (OSError, ValueError, KeyError, TypeError) as error:
            result.update(status='failed', failures=[{'path': str(state_path), 'error': str(error)}]); return result
        for turn, card, edit in zip(row['turns'], videos[1:], edits):
            tid = turn['turn_id']; td = directory / f'turn_{tid:02d}'
            try:
                progress = read(td / 'progress.json'); request = progress['request']; parent = request['source_video_id']
                require(type(parent) is int and 0 <= parent < tid, td, 'source ID is not an earlier actual video')
                record = self.generation(td, progress); actual = record['request']
                require(same_path(actual['source_video'], videos[parent]['video_path']), td, 'source was replaced by another video or GT')
                require(actual['references'] == turn['references'], td, 'current references differ from public input')
                require(actual['prompt'].strip() == request['prompt'].strip(), td, 'executed prompt differs from Qwen request')
                require(actual.get('seed', 42) == state['identity']['config']['seed'], td, 'generation seed differs')
                require(request['reference_ids'] == [r['reference_id'] for r in turn['references']], td, 'reference IDs/order differ')
                require(card['video_id'] == tid and card['parent_id'] == parent and same_path(card['video_path'], record['video_path']), td, 'card ID/parent/path differs')
                require(read(directory / f'videos/video_{tid:03d}.json') == card, td, 'video record differs from final history')
                require(read(directory / f'edits/edit_{tid:03d}.json') == edit and edit['source_video_id'] == parent and
                        edit['output_video_id'] == tid and edit['user_prompt'] == turn['user_prompt'] and
                        edit['editing_prompt'] == request['prompt'] and edit['reference_ids'] == request['reference_ids'] and
                        edit['review'] == progress['review']['review'], td, 'edit record differs')
                observation = self.output_observation(td, progress, card, state)
                result['turns'].append({'turn_id': tid, 'parent_id': parent, 'video_sha256': record['video_sha256'],
                                        'reused': bool(progress['generation'].get('reuse_provenance')), 'observation': observation})
            except (OSError, ValueError, KeyError, TypeError, subprocess.SubprocessError) as error:
                result['status'] = 'failed'; result['failures'].append({'path': str(td), 'error': str(error)})
        return result


def audit(run, rows, *, probe=False, legacy_v2=False):
    auditor = Auditor(run, probe=probe, legacy_v2=legacy_v2)
    results = []
    for row in rows:
        try:
            results.append(auditor.chain(row))
        except (OSError, ValueError, KeyError, TypeError) as error:
            results.append({'id': row.get('chain_id'), 'status': 'failed', 'turns': [],
                            'failures': [{'path': str(auditor.run / 'cases' / row['chain_id']), 'error': str(error)}]})
    completed = [r for r in results if r['status'] != 'skipped_not_completed']
    return {'schema': 'editing_agent_runtime_audit_v1', 'checked_unix': time.time(),
            'scope': 'legacy_v2_without_independent_observation' if legacy_v2 else 'v3_independent_output_observation',
            'success': bool(completed) and all(r['status'] == 'passed' for r in completed),
            'all_requested_chains_completed': len(completed) == len(rows), 'completed_chains_checked': len(completed),
            'media_probe': probe, 'probe_results': auditor.probed, 'cases': results,
            'quality_or_label_correctness_scored': False}


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--run', type=Path, required=True); parser.add_argument('--dataset', type=Path, required=True)
    parser.add_argument('--output', type=Path); parser.add_argument('--probe', action='store_true')
    parser.add_argument('--legacy-v2', action='store_true'); args = parser.parse_args()
    rows = [json.loads(line) for line in args.dataset.read_text().splitlines() if line.strip()]
    result = audit(args.run, rows, probe=args.probe, legacy_v2=args.legacy_v2)
    output = args.output or args.run / 'report/runtime_audit.json'; output.parent.mkdir(parents=True, exist_ok=True)
    temporary = output.with_suffix('.json.tmp'); temporary.write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n'); temporary.replace(output)
    print(json.dumps({'output': str(output), 'success': result['success'], 'completed_checked': result['completed_chains_checked'],
                      'all_requested_completed': result['all_requested_chains_completed'], 'scope': result['scope']}))
    raise SystemExit(0 if result['success'] else 1)


if __name__ == '__main__':
    main()
